import java.util.Random;

// Writes test/java/LongFuzzCheck.java, random methods on longs whose results
// HotSpot and champaca must agree on: arithmetic, shifts by literal and
// computed counts, comparisons as branches and as values, conditional
// expressions (a long on the stack where blocks join), x++ (dup2), long
// arrays and fields, calls, a division in a try whose catch reads the locals
// (method-wide locals), parameters assigned and read. Rerun after changing
// it, then record the .expected with HotSpot:
//   java test/fuzz/LongFuzzGen.java 84 > test/java/LongFuzzCheck.java
public class LongFuzzGen {
    static Random r;
    static final String[] LOCALS = {"a", "b", "x", "y", "z"};
    static final String[] CONSTS = {"0L", "1L", "-1L", "2L", "0x7fffffffL", "0x80000000L", "0xffffffffL",
        "0x100000000L", "-0x80000000L", "(1L << 60)", "(1L << 60) - 1", "-(1L << 60)", "Long.MAX_VALUE",
        "Long.MIN_VALUE", "0x9E3779B97F4A7C15L", "0xff51afd7ed558ccdL", "31L", "1000003L", "0x5DEECE66DL"};

    static String pick(String[] xs) { return xs[r.nextInt(xs.length)]; }

    static String count() {
        switch (r.nextInt(4)) {
            case 0: return String.valueOf(r.nextInt(70));
            case 1: return "n";
            case 2: return "(int) " + atom();
            default: return "(n + " + r.nextInt(64) + ")";
        }
    }

    static String atom() {
        switch (r.nextInt(6)) {
            case 0: case 1: case 2: return pick(LOCALS);
            case 3: return pick(CONSTS);
            case 4: return "(long) n";
            default: return "(long) i";
        }
    }

    static String expr(int depth) {
        if (depth <= 0 || r.nextInt(4) == 0) return atom();
        String e1 = expr(depth - 1), e2 = expr(depth - 1);
        switch (r.nextInt(20)) {
            case 0: case 1: return "(" + e1 + " + " + e2 + ")";
            case 2: case 3: return "(" + e1 + " - " + e2 + ")";
            case 4: case 5: return "(" + e1 + " * " + e2 + ")";
            case 6: return "(" + e1 + " & " + e2 + ")";
            case 7: return "(" + e1 + " | " + e2 + ")";
            case 8: return "(" + e1 + " ^ " + e2 + ")";
            case 9: return "(" + e1 + " << " + count() + ")";
            case 10: return "(" + e1 + " >> " + count() + ")";
            case 11: return "(" + e1 + " >>> " + count() + ")";
            case 12: return "(- " + e1 + ")";
            case 13: return "(~" + e1 + ")";
            case 14: return "((long) (int) " + e1 + ")";
            case 15: return "(" + e1 + " / (" + e2 + " | 1L))";
            case 16: return "(" + e1 + " % (" + e2 + " | 1L))";
            case 17: return "(" + e1 + " " + pick(new String[] {"<", "<=", ">", ">=", "==", "!="}) + " " + e2
                + " ? " + expr(depth - 1) + " : " + expr(depth - 1) + ")";
            case 18: return "mix(" + e1 + ", " + e2 + ")";
            default: return "((long) Long.compare(" + e1 + ", " + e2 + "))";
        }
    }

    static String stmt(int depth) {
        String v = pick(LOCALS);
        switch (r.nextInt(14)) {
            case 0: case 1: case 2: return v + " = " + expr(depth) + ";";
            case 3: return v + " " + pick(new String[] {"+=", "-=", "*=", "^=", "&=", "|="}) + " " + expr(depth) + ";";
            case 4: return v + " " + pick(new String[] {"<<=", ">>=", ">>>="}) + " " + count() + ";";
            case 5: return pick(LOCALS) + " = " + v + (r.nextBoolean() ? "++" : "--") + " + " + expr(depth - 1) + ";";
            case 6: return "if (" + expr(depth - 1) + " " + pick(new String[] {"<", "<=", ">", ">=", "==", "!="}) + " "
                + expr(depth - 1) + ") " + v + " = " + expr(depth - 1) + "; else " + pick(LOCALS) + " ^= "
                + expr(depth - 1) + ";";
            case 7: return "arr[i & 1] " + pick(new String[] {"+=", "^=", "*="}) + " " + expr(depth) + "; " + v
                + " += arr[(i + 1) & 1];";
            case 8: return "field " + pick(new String[] {"+=", "^=", "-="}) + " " + expr(depth) + "; " + v + " ^= field;";
            case 9: return "i = (int) " + expr(depth) + ";";
            case 10: return "if (" + expr(depth - 1) + " < " + expr(depth - 1) + ") i++;";
            case 11: return "try { " + v + " = " + expr(depth - 1) + " / " + pick(LOCALS) + "; } catch (ArithmeticException e) { "
                + v + " = " + pick(LOCALS) + " + 7; }";
            case 12: return v + " = (long) (double) " + expr(depth - 1) + ";";
            default: return v + " = " + expr(depth - 1) + " > " + expr(depth - 1) + " ? " + v + " : " + expr(depth - 1) + ";";
        }
    }

    public static void main(String[] args) {
        long seed = Long.parseLong(args[0]);
        r = new Random(seed);
        int methods = 60;
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by test/fuzz/LongFuzzGen.java with seed ").append(seed).append("; don't edit.\n");
        sb.append("public class LongFuzzCheck {\n");
        sb.append("    static long field;\n");
        sb.append("    static long mix(long p, long q) { return p * 31 ^ (q >>> 7); }\n");
        for (int m = 0; m < methods; m++) {
            sb.append("    static long f").append(m).append("(long a, long b, int n) {\n");
            sb.append("        int i = n;\n");
            sb.append("        long x = 0, y = 0, z = 0;\n");
            sb.append("        x = ").append(expr(2)).append(";\n");
            sb.append("        y = ").append(expr(2)).append(";\n");
            sb.append("        long[] arr = {a, b};\n");
            sb.append("        for (int k = 0; k < 3; k++) {\n");
            int stmts = 3 + r.nextInt(5);
            for (int s = 0; s < stmts; s++) sb.append("            ").append(stmt(3)).append("\n");
            sb.append("        }\n");
            sb.append("        return ").append(expr(3)).append(" ^ x ^ y * 3 ^ z * 5 ^ i;\n");
            sb.append("    }\n");
        }
        sb.append("    static final long[] VALS = {0L, 1L, -1L, 7L, 0x7fffffffL, 0x80000000L, 0xffffffffL, -0x80000001L,\n");
        sb.append("        (1L << 60) - 1, 1L << 60, -(1L << 60) - 1, Long.MAX_VALUE, Long.MIN_VALUE, 0x123456789abcdefL};\n");
        sb.append("    static final int[] NS = {0, 5, 31, 33, 63, 64, -1};\n");
        sb.append("    public static void main(String[] args) {\n");
        sb.append("        boolean all = args.length > 0;\n");
        for (int m = 0; m < methods; m++) {
            sb.append("        { long h = 0; for (long a : VALS) for (long b : VALS) for (int n : NS) { field = a; long v = f")
              .append(m).append("(a, b, n); if (all) System.out.println(\"f").append(m)
              .append(" \" + a + \" \" + b + \" \" + n + \" \" + v); h = h * 1000003L ^ v; } System.out.println(\"f")
              .append(m).append(" \" + h); }\n");
        }
        sb.append("    }\n}\n");
        System.out.print(sb);
    }
}
